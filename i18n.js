(function () {
  'use strict';
  var reduce = window.matchMedia &&
    window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function initGallery(root) {
    var viewport = root.querySelector('.gallery__viewport');
    var track = root.querySelector('.gallery__track');
    if (!viewport || !track) return;
    var slides = Array.prototype.slice.call(track.querySelectorAll('.gallery__slide'));
    if (!slides.length) return;

    var prevBtn = root.querySelector('.gallery__arrow--prev');
    var nextBtn = root.querySelector('.gallery__arrow--next');
    var dotsWrap = root.querySelector('.gallery__dots');
    var dots = [];

    // 動態建立進度點（依 slide 數）
    if (dotsWrap) {
      dotsWrap.innerHTML = '';
      slides.forEach(function (s, i) {
        var d = document.createElement('button');
        d.type = 'button';
        d.className = 'gallery__dot';
        d.setAttribute('aria-label', '第 ' + (i + 1) + ' 張');
        d.addEventListener('click', function () { goTo(i); });
        dotsWrap.appendChild(d);
        dots.push(d);
      });
    }

    function slideStep() {
      // 一次捲動一張（含 gap）
      if (slides.length < 2) return slides[0].offsetWidth;
      return slides[1].offsetLeft - slides[0].offsetLeft;
    }

    function activeIndex() {
      var center = viewport.scrollLeft + viewport.clientWidth / 2;
      var best = 0, bestDist = Infinity;
      slides.forEach(function (s, i) {
        var sc = s.offsetLeft + s.offsetWidth / 2;
        var d = Math.abs(sc - center);
        if (d < bestDist) { bestDist = d; best = i; }
      });
      return best;
    }

    function goTo(i) {
      i = Math.max(0, Math.min(slides.length - 1, i));
      var target = slides[i].offsetLeft -
        (viewport.clientWidth - slides[i].offsetWidth) / 2;
      viewport.scrollTo({
        left: Math.max(0, target),
        behavior: reduce ? 'auto' : 'smooth'
      });
    }

    function update() {
      var idx = activeIndex();
      dots.forEach(function (d, i) {
        d.classList.toggle('is-active', i === idx);
      });
      var atStart = viewport.scrollLeft <= 2;
      var atEnd = viewport.scrollLeft + viewport.clientWidth >=
        track.scrollWidth - 2;
      if (prevBtn) prevBtn.disabled = atStart;
      if (nextBtn) nextBtn.disabled = atEnd;
    }

    if (prevBtn) prevBtn.addEventListener('click', function () {
      viewport.scrollBy({ left: -slideStep(), behavior: reduce ? 'auto' : 'smooth' });
    });
    if (nextBtn) nextBtn.addEventListener('click', function () {
      viewport.scrollBy({ left: slideStep(), behavior: reduce ? 'auto' : 'smooth' });
    });

    var raf = null;
    viewport.addEventListener('scroll', function () {
      if (raf) return;
      raf = requestAnimationFrame(function () { raf = null; update(); });
    }, { passive: true });
    window.addEventListener('resize', update, { passive: true });

    update();

    // 讓每張圖可點擊放大（燈箱）
    slides.forEach(function (s, i) {
      var img = s.querySelector('.gallery__img');
      if (!img) return;
      img.classList.add('gallery__img--zoomable');
      img.setAttribute('role', 'button');
      img.setAttribute('tabindex', '0');
      img.setAttribute('aria-label', '放大檢視第 ' + (i + 1) + ' 張');
      img.addEventListener('click', function () { openLightbox(slides, i); });
      img.addEventListener('keydown', function (e) {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          openLightbox(slides, i);
        }
      });
    });
  }

  /* ── 燈箱（全螢幕放大檢視）────────────────────────── */
  var lb = null;
  var lbState = { slides: [], index: 0 };

  function buildLightbox() {
    if (lb) return lb;
    lb = document.createElement('div');
    lb.className = 'gallery-lightbox';
    lb.setAttribute('role', 'dialog');
    lb.setAttribute('aria-modal', 'true');
    lb.setAttribute('aria-label', '圖片放大檢視');
    lb.innerHTML =
      '<div class="gallery-lightbox__backdrop"></div>' +
      '<button type="button" class="gallery-lightbox__close" aria-label="關閉">&times;</button>' +
      '<button type="button" class="gallery-lightbox__nav gallery-lightbox__nav--prev" aria-label="上一張">&#8249;</button>' +
      '<button type="button" class="gallery-lightbox__nav gallery-lightbox__nav--next" aria-label="下一張">&#8250;</button>' +
      '<figure class="gallery-lightbox__figure">' +
        '<img class="gallery-lightbox__img" alt="" />' +
        '<figcaption class="gallery-lightbox__caption"></figcaption>' +
      '</figure>' +
      '<div class="gallery-lightbox__counter"></div>';
    document.body.appendChild(lb);

    lb.querySelector('.gallery-lightbox__backdrop')
      .addEventListener('click', closeLightbox);
    lb.querySelector('.gallery-lightbox__close')
      .addEventListener('click', closeLightbox);
    lb.querySelector('.gallery-lightbox__nav--prev')
      .addEventListener('click', function () { stepLightbox(-1); });
    lb.querySelector('.gallery-lightbox__nav--next')
      .addEventListener('click', function () { stepLightbox(1); });
    return lb;
  }

  function renderLightbox() {
    var slide = lbState.slides[lbState.index];
    if (!slide) return;
    var srcImg = slide.querySelector('.gallery__img');
    var cap = slide.querySelector('.gallery__caption');
    var img = lb.querySelector('.gallery-lightbox__img');
    img.src = srcImg.getAttribute('src');
    img.alt = srcImg.getAttribute('alt') || '';
    var capText = '';
    if (cap) {
      var tag = cap.querySelector('.gallery__tag');
      if (tag) {
        var tagText = tag.textContent.trim();
        var rest = cap.textContent.replace(tagText, '').trim();
        capText = tagText ? (tagText + '・' + rest) : rest;
      } else {
        capText = cap.textContent.trim();
      }
    }
    lb.querySelector('.gallery-lightbox__caption').textContent = capText;
    lb.querySelector('.gallery-lightbox__counter').textContent =
      (lbState.index + 1) + ' / ' + lbState.slides.length;
    var prev = lb.querySelector('.gallery-lightbox__nav--prev');
    var next = lb.querySelector('.gallery-lightbox__nav--next');
    var multi = lbState.slides.length > 1;
    prev.style.display = multi ? '' : 'none';
    next.style.display = multi ? '' : 'none';
  }

  function openLightbox(slides, index) {
    buildLightbox();
    lbState.slides = slides;
    lbState.index = index;
    renderLightbox();
    lb.classList.add('is-open');
    document.body.classList.add('gallery-lightbox-open');
    document.addEventListener('keydown', onLightboxKey);
  }

  function closeLightbox() {
    if (!lb) return;
    lb.classList.remove('is-open');
    document.body.classList.remove('gallery-lightbox-open');
    document.removeEventListener('keydown', onLightboxKey);
  }

  function stepLightbox(dir) {
    if (!lbState.slides.length) return;
    var n = lbState.slides.length;
    lbState.index = (lbState.index + dir + n) % n;
    renderLightbox();
  }

  function onLightboxKey(e) {
    if (e.key === 'Escape') closeLightbox();
    else if (e.key === 'ArrowLeft') stepLightbox(-1);
    else if (e.key === 'ArrowRight') stepLightbox(1);
  }

  function boot() {
    document.querySelectorAll('.gallery').forEach(initGallery);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot);
  } else {
    boot();
  }
})();
